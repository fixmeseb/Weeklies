#!/usr/bin/env python3
"""Rebuild proj2/fndds_foods.py: the USDA foods the demo menu's nutrition comes from.

proj2/demo_nutrition.py matches each demo dish to foods in USDA FoodData Central's
Survey (FNDDS) dataset. This script reads the dataset's bulk CSV download and writes the
nutrient values of just those foods, per 100 g, into a Python module, so seeding and the
tests never need the network or an API key.

Usage:
    1. Download and unzip the "Survey (FNDDS)" CSV from
       https://fdc.nal.usda.gov/download-datasets/ (the snapshot was built from the
       2024-10-31 release, FoodData_Central_survey_food_csv_2024-10-31.zip).
    2. python scripts/build_fndds_snapshot.py <unzipped folder>

USDA FoodData Central data is public domain (CC0 1.0).
"""

import csv
import os
import pprint
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from proj2.demo_nutrition import MATCHES  # noqa: E402

OUTPUT = os.path.join(ROOT, "proj2", "fndds_foods.py")

## FNDDS nutrient numbers (food_nutrient.csv's nutrient_id column) -> our field names
NUTRIENTS = {
    "208": "kcal",
    "203": "protein_g",
    "205": "carbs_g",
    "204": "fat_g",
    "307": "sodium_mg",
}

HEADER = '''"""
USDA FoodData Central foods used by proj2/demo_nutrition.py, per 100 g.

Generated by scripts/build_fndds_snapshot.py from the Survey (FNDDS) {release} release;
do not edit by hand. Source: U.S. Department of Agriculture, Agricultural Research
Service, FoodData Central (https://fdc.nal.usda.gov/), public domain (CC0 1.0).
"""

RELEASE = {release!r}

'''


def read_foods(folder: str, wanted: set) -> dict:
    """fdc_id -> {"description", "kcal", "protein_g", "carbs_g", "fat_g", "sodium_mg"}."""
    foods = {}
    with open(os.path.join(folder, "food.csv"), newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            fdc_id = int(row["fdc_id"])
            if fdc_id in wanted:
                foods[fdc_id] = {"description": row["description"]}
    with open(os.path.join(folder, "food_nutrient.csv"), newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            field = NUTRIENTS.get(row["nutrient_id"])
            fdc_id = int(row["fdc_id"])
            if field and fdc_id in foods:
                foods[fdc_id][field] = float(row["amount"])
    missing = sorted(wanted - set(foods))
    incomplete = sorted(i for i, food in foods.items() if len(food) != len(NUTRIENTS) + 1)
    if missing or incomplete:
        raise SystemExit(f"not in the download: {missing}; missing nutrients: {incomplete}")
    return foods


def main(argv) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    folder = argv[1]
    release = os.path.basename(os.path.normpath(folder)).rsplit("_", 1)[-1]
    wanted = {fdc_id for parts in MATCHES.values() for fdc_id, _ in parts}
    foods = read_foods(folder, wanted)
    with open(OUTPUT, "w", encoding="utf-8") as out:
        out.write(HEADER.format(release=release))
        out.write("FOODS = ")
        out.write(pprint.pformat(dict(sorted(foods.items())), width=96, sort_dicts=False))
        out.write("\n")
    print(f"wrote {len(foods)} foods to {os.path.relpath(OUTPUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
